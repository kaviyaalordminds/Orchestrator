/* ============================================
   WORD AGENT — AI Document Studio
   Dedicated workspace for generating, editing
   and exporting professional documents
   ============================================ */

const wordAgent = {
  _exportUrl: null,
  _content: '',

  onActivate() {
    // No auto-init needed; workspace is ready
  },

  async generate() {
    const topicEl = document.getElementById('wordTopic');
    const topic = topicEl?.value.trim();
    if (!topic) {
      app.showToast('Topic Required', 'Please enter a document topic.', 'warning');
      return;
    }

    const btn = document.getElementById('wordGenerateBtn');
    if (btn) { btn.disabled = true; btn.innerHTML = '<i class="bi bi-hourglass-split"></i> Generating...'; }

    try {
      const payload = {
        topic,
        doc_type: document.getElementById('wordDocType')?.value || 'Business Report',
        content: document.getElementById('wordContent')?.value || '',
        language: document.getElementById('wordLanguage')?.value || 'English',
        tone: document.getElementById('wordTone')?.value || 'Professional',
        template: document.getElementById('wordTemplate')?.value || 'Clean White',
        headings: document.getElementById('wordHeadings')?.checked ?? true,
        tables: document.getElementById('wordTables')?.checked ?? false,
        toc: document.getElementById('wordTOC')?.checked ?? false,
        page_numbers: document.getElementById('wordPageNum')?.checked ?? false
      };

      const token = localStorage.getItem('jwt_token');
      const headers = {
        'Content-Type': 'application/json',
        ...(token ? { 'Authorization': 'Bearer ' + token } : {})
      };

      const res = await fetch(`${app.apiBase}/api/v1/word/generate`, {
        method: 'POST', headers, body: JSON.stringify(payload)
      });
      const data = await res.json();

      if (data.success) {
        this._exportUrl = data.data.file_url;
        this._content = data.data.content_html || data.data.content || this._buildMockDoc(topic, payload);
        this._renderPreview();
        app.showToast('Document Ready!', 'Your document has been generated.', 'success');
      } else {
        throw new Error(data.error?.message || 'Generation failed');
      }
    } catch (err) {
      this._content = this._buildMockDoc(topic, {});
      this._renderPreview();
      app.showToast('Document Created', 'Preview ready. Connect backend for DOCX export.', 'info');
    } finally {
      if (btn) { btn.disabled = false; btn.innerHTML = '<i class="bi bi-magic"></i> Generate Document'; }
    }
  },

  _buildMockDoc(topic, opts) {
    const date = new Date().toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' });
    const docType = opts.doc_type || 'Business Report';
    const tone = opts.tone || 'Professional';

    return `
      <div style="margin-bottom:32px;padding-bottom:24px;border-bottom:2px solid #6366f1;">
        <h1 style="font-size:28px;font-weight:700;color:#111;margin-bottom:8px;">${topic}</h1>
        <p style="color:#888;font-size:13px;">${docType} &nbsp;&bull;&nbsp; ${tone} Tone &nbsp;&bull;&nbsp; ${date}</p>
        <p style="color:#888;font-size:12px;margin-top:4px;">Generated by AI Document Studio &mdash; Lordminds</p>
      </div>

      <h2 style="font-size:20px;font-weight:700;color:#1e293b;margin:32px 0 12px;padding-left:12px;border-left:4px solid #6366f1;">Executive Summary</h2>
      <p style="line-height:1.8;color:#374151;">This document provides a comprehensive and professionally structured overview of <strong>${topic}</strong>. It has been crafted to deliver maximum clarity and strategic value, tailored for the intended audience and business context.</p>

      <h2 style="font-size:20px;font-weight:700;color:#1e293b;margin:32px 0 12px;padding-left:12px;border-left:4px solid #6366f1;">Introduction</h2>
      <p style="line-height:1.8;color:#374151;">In today's competitive landscape, <strong>${topic}</strong> represents a critical area of strategic focus. This document aims to outline key considerations, provide data-driven insights, and present actionable recommendations for stakeholders.</p>

      <h2 style="font-size:20px;font-weight:700;color:#1e293b;margin:32px 0 12px;padding-left:12px;border-left:4px solid #6366f1;">Key Points</h2>
      <ul style="line-height:2.2;color:#374151;padding-left:24px;">
        <li>Strategic importance and measurable business impact</li>
        <li>Current market landscape and competitive analysis</li>
        <li>Data-driven insights and evidence-based recommendations</li>
        <li>Implementation roadmap and success metrics</li>
        <li>Risk assessment and mitigation strategies</li>
      </ul>

      <h2 style="font-size:20px;font-weight:700;color:#1e293b;margin:32px 0 12px;padding-left:12px;border-left:4px solid #6366f1;">Analysis & Recommendations</h2>
      <p style="line-height:1.8;color:#374151;">Based on the available data and strategic context, the following recommendations are proposed. Each recommendation has been evaluated against feasibility, impact potential, and resource requirements to ensure practical applicability.</p>
      <p style="line-height:1.8;color:#374151;margin-top:12px;">The primary recommendation focuses on leveraging existing capabilities while building toward a long-term strategic position in the ${topic.toLowerCase()} domain.</p>

      <h2 style="font-size:20px;font-weight:700;color:#1e293b;margin:32px 0 12px;padding-left:12px;border-left:4px solid #6366f1;">Conclusion</h2>
      <p style="line-height:1.8;color:#374151;">The findings presented in this document clearly demonstrate that ${topic} offers significant strategic opportunities. The recommendations outlined above provide a clear, actionable path forward. Timely execution is recommended to maximize competitive advantage.</p>
    `;
  },

  _renderPreview() {
    const preview = document.getElementById('wordDocPreview');
    if (preview) preview.innerHTML = this._content;
  },

  async editDocument() {
    const prompt = document.getElementById('wordEditPrompt')?.value?.trim();
    if (!prompt) { app.showToast('Enter a prompt', 'Describe the edit you want.', 'warning'); return; }
    if (!this._content) { app.showToast('No Document', 'Generate a document first.', 'warning'); return; }

    app.showToast('AI Editing', 'Applying your changes...', 'info');

    // Simulate AI edit by appending a styled note
    this._content += `
      <div style="margin-top:28px;padding:16px;background:#f8f7ff;border-left:4px solid #6366f1;border-radius:4px;">
        <p style="font-size:12px;color:#6366f1;font-weight:600;margin-bottom:4px;">AI EDIT</p>
        <p style="color:#374151;font-size:14px;line-height:1.7;">${prompt}</p>
      </div>`;
    this._renderPreview();
    document.getElementById('wordEditPrompt').value = '';
  },

  regenerate() {
    this.generate();
  },

  exportDocx() {
    if (this._exportUrl) {
      window.open('http://localhost:8000' + this._exportUrl, '_blank');
    } else {
      app.showToast('No Export', 'Generate a document first to export.', 'warning');
    }
  },

  exportPdf() {
    app.showToast('PDF Export', 'Requires backend connection to generate PDF.', 'info');
  }
};
